class _HelpSection {
  final IconData icon;
  final String title;
  final String body;

  /// Real app screenshot (English interface) bundled in assets/help/,
  /// generated by test/help_screenshots_test.dart.
  final String? screenshot;
  final Widget? figure;
  final List<String> legend;

  const _HelpSection({
    required this.icon,
    required this.title,
    required this.body,
    this.screenshot,
    this.figure,
    this.legend = const [],
  });
}

class _IntroCard extends StatelessWidget {
  final String text;
  const _IntroCard({required this.text});

  @override
  Widget build(BuildContext context) {
    return Card(
      color: GmhColors.ember.withValues(alpha: 0.09),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Row(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Icon(Icons.auto_stories_outlined,
                size: 26, color: GmhColors.ember),
            const SizedBox(width: 14),
            Expanded(
              child: Text(text, style: const TextStyle(height: 1.45)),
            ),
          ],
        ),
      ),
    );
  }
}

class _SectionCard extends StatelessWidget {
  final _HelpSection section;
  const _SectionCard({required this.section});

  @override
  Widget build(BuildContext context) {
    return Card(
      clipBehavior: Clip.antiAlias,
      child: ExpansionTile(
        leading: Icon(section.icon, size: 21, color: GmhColors.ember),
        title: Text(section.title,
            style: const TextStyle(fontWeight: FontWeight.w600)),
        childrenPadding: const EdgeInsets.fromLTRB(16, 0, 16, 16),
        expandedCrossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(section.body, style: const TextStyle(height: 1.45)),
          if (section.screenshot != null) ...[
            const SizedBox(height: 14),
            Center(
              child: ConstrainedBox(
                constraints: const BoxConstraints(maxWidth: 760),
                child: Container(
                  decoration: BoxDecoration(
                    borderRadius: BorderRadius.circular(10),
                    border: Border.all(
                        color:
                            GmhColors.parchmentDim.withValues(alpha: 0.4)),
                  ),
                  clipBehavior: Clip.antiAlias,
                  child: Image.asset(
                    'assets/help/${section.screenshot!}.png',
                    fit: BoxFit.contain,
                  ),
                ),
              ),
            ),
            const SizedBox(height: 6),
            Center(
              child: Text(
                context.l10n.helpScreenshotCaption,
                style: TextStyle(
                    fontSize: 11,
                    fontStyle: FontStyle.italic,
                    color: GmhColors.parchmentDim),
              ),
            ),
          ],
          if (section.figure != null) ...[
            const SizedBox(height: 14),
            Center(
              child: ConstrainedBox(
                constraints: const BoxConstraints(maxWidth: 560),
                child: section.figure!,
              ),
            ),
            const SizedBox(height: 6),
            Center(
              child: Text(
                context.l10n.helpFigureCaption,
                style: TextStyle(
                    fontSize: 11,
                    fontStyle: FontStyle.italic,
                    color: GmhColors.parchmentDim),
              ),
            ),
            const SizedBox(height: 6),
            for (var i = 0; i < section.legend.length; i++)
              Padding(
                padding: const EdgeInsets.only(top: 6),
                child: Row(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    _Marker(number: i + 1, small: true),
                    const SizedBox(width: 8),
                    Expanded(
                      child: Text(section.legend[i],
                          style: const TextStyle(
                              fontSize: 12.5, height: 1.4)),
                    ),
                  ],
                ),
              ),
          ],
        ],
      ),
    );
  }
}

// ==================================================================
// Schematic figures — miniature replicas of real screens, annotated
// with numbered markers that the legend below explains.
// ==================================================================

class _Marker extends StatelessWidget {
  final int number;
  final bool small;
  const _Marker({required this.number, this.small = false});

  @override
  Widget build(BuildContext context) {
    final size = small ? 18.0 : 20.0;
    return Container(
      width: size,
      height: size,
      alignment: Alignment.center,
      decoration: BoxDecoration(
        color: GmhColors.ember,
        shape: BoxShape.circle,
      ),
      child: Text(
        '$number',
        style: TextStyle(
          fontSize: small ? 11 : 12,
          fontWeight: FontWeight.w700,
          color: Theme.of(context).colorScheme.onPrimary,
        ),
      ),
    );
  }
}

class _FigureFrame extends StatelessWidget {
  final Widget child;
  final double aspectRatio;
  const _FigureFrame({required this.child, this.aspectRatio = 16 / 10});

  @override
  Widget build(BuildContext context) {
    return AspectRatio(
      aspectRatio: aspectRatio,
      child: Container(
        decoration: BoxDecoration(
          color: GmhColors.background,
          borderRadius: BorderRadius.circular(10),
          border: Border.all(
              color: GmhColors.parchmentDim.withValues(alpha: 0.4)),
        ),
        clipBehavior: Clip.antiAlias,
        child: child,
      ),
    );
  }
}

/// Grey placeholder bar imitating a line of text.
class _Bar extends StatelessWidget {
  final double width;
  final double height;
  final Color? color;
  const _Bar(this.width, {this.height = 7, this.color});

  @override
  Widget build(BuildContext context) {
    return Container(
      width: width,
      height: height,
      decoration: BoxDecoration(
        color: color ?? GmhColors.parchmentDim.withValues(alpha: 0.45),
        borderRadius: BorderRadius.circular(3),
      ),
    );
  }
}

class _MockTile extends StatelessWidget {
  final IconData icon;
  final bool selected;
  const _MockTile({required this.icon, this.selected = false});

  @override
  Widget build(BuildContext context) {
    return Container(
      margin: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
      padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 4),
      decoration: BoxDecoration(
        color: selected
