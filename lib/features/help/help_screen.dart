      _HelpSection(
        icon: Icons.view_sidebar_outlined,
        title: l.helpShellTitle,
        body: l.helpShellBody,
        screenshot: 'shell_list',
        figure: const _ShellFigure(),
        legend: [
          l.helpShellLegend1,
          l.helpShellLegend2,
          l.helpShellLegend3,
          l.helpShellLegend4,
          l.helpShellLegend5,
          l.helpShellLegend6,
        ],
      ),
      _HelpSection(
        icon: Icons.article_outlined,
        title: l.helpEntryTitle,
        body: l.helpEntryBody,
        screenshot: 'entry',
        figure: const _EntryFigure(),
        legend: [
          l.helpEntryLegend1,
          l.helpEntryLegend2,
          l.helpEntryLegend3,
          l.helpEntryLegend4,
          l.helpEntryLegend5,
        ],
      ),
      _HelpSection(
        icon: Icons.person_outline,
        title: l.helpProfileTitle,
        body: l.helpProfileBody,
        screenshot: 'profile',
      ),
      _HelpSection(
        icon: Icons.map_outlined,
        title: l.helpCampaignsTitle,
        body: l.helpCampaignsBody,
        screenshot: 'campaigns',
      ),
      _HelpSection(
        icon: Icons.search,
        title: l.helpSearchTitle,
        body: l.helpSearchBody,
        screenshot: 'search',
      ),
      _HelpSection(
        icon: Icons.hub_outlined,
        title: l.helpGraphTitle,
        body: l.helpGraphBody,
        screenshot: 'graph',
